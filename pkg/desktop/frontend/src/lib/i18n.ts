const catalogs: Record<Lang, Record<string, string>> = { en, tr };

export function translate(lang: string, key: string, vars?: Record<string, string | number>): string {
  const table = catalogs[(lang as Lang) in catalogs ? (lang as Lang) : 'en'];
  let value = table[key] ?? en[key] ?? key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}

export function useT(): (key: string, vars?: Record<string, string | number>) => string {
  const language = useStore((state) => state.language);
  return (key, vars) => translate(language, key, vars);
}

export function greetingKey(date = new Date()): string {
  const hour = date.getHours();
  if (hour < 5) return 'welcome.night';
  if (hour < 12) return 'welcome.morning';
  if (hour < 18) return 'welcome.afternoon';
  return 'welcome.evening';
}
